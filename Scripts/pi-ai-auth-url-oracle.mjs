import {readFileSync} from "node:fs";
import {execFileSync} from "node:child_process";
import path from "node:path";
import {pathToFileURL} from "node:url";
const [root,input] = process.argv.slice(2);
const fixture=JSON.parse(readFileSync(input,"utf8"));
const revision=execFileSync("git",["-C",root,"rev-parse","HEAD"],{encoding:"utf8"}).trim();
if (revision!==fixture.upstreamRevision) throw new Error("auth URL revision mismatch");
const {trustedHttpUrl}=await import(pathToFileURL(path.join(root,"packages/ai/src/auth/oauth/trusted-url.ts")));
console.log(JSON.stringify({upstreamRevision:revision,cases:fixture.cases.map(c=>({...c,normalized:trustedHttpUrl(c.url)}))},null,2));
